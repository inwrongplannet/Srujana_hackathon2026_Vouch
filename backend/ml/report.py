"""Render `results/metrics.json` as a markdown report."""

from __future__ import annotations

import json
import os

RESULTS_DIR = os.path.join(os.path.dirname(__file__), "results")


def _row(name: str, m: dict) -> str:
    return (
        f"| {name} | {m['n']} | {m['auc']:.4f} | {m['pr_auc']:.4f} | {m['brier']:.4f} "
        f"| {m['ks']:.4f} | {m['accuracy_at_threshold']:.4f} | {m['f1']:.4f} | {m['approval_rate']:.3f} |"
    )


def write_report(results: dict) -> None:
    lines: list[str] = []
    add = lines.append

    add("# Model results\n")
    add("Generated by `python -m ml.train`. Illustrative data; not financial advice.\n")
    add(f"Features used: **{results['dataset']['n_features']}** (money in integer paise, ratios as decimals).\n")

    for source in ("real_anchored", "simulated"):
        block = results[source]
        add(f"\n## {source.replace('_', ' ').title()} ({block['source']})\n")
        add("| Model | n | AUC | PR-AUC | Brier | KS | Accuracy | F1 | Approval rate |")
        add("|---|---|---|---|---|---|---|---|---|")
        for name, m in block["models"].items():
            add(_row(name, m["test"]))
        add("")

        conf = block["conformal"].get("lightgbm", {})
        add("### Conformal prediction, LightGBM (target 1 - alpha coverage)\n")
        add("| Score | Alpha | Threshold | Coverage | Avg set size | Singleton | Both labels |")
        add("|---|---|---|---|---|---|---|")
        for key, val in conf.items():
            if key.startswith("mondrian"):
                continue
            t = val["test"]
            alpha = "0.10" if key.endswith("90") else "0.05"
            add(f"| {key.split('_')[0].upper()} | {alpha} | {val['threshold']:.4f} | {t['coverage']:.4f} "
                f"| {t['avg_set_size']:.3f} | {t['singleton_rate']:.3f} | {t['both_label_rate']:.3f} |")
        add("")

        mond = conf.get("mondrian_lac_90")
        if mond:
            add("### Conditional coverage by completeness tier (Mondrian, LAC, 90%)\n")
            add("| Tier | n | Coverage | Avg set size | Singleton |")
            add("|---|---|---|---|---|")
            for tier, t in mond["per_completeness_tier"].items():
                add(f"| {tier} | {t['n']} | {t['coverage']:.4f} | {t['avg_set_size']:.3f} | {t['singleton_rate']:.3f} |")
            add("")
            add("Threshold per tier: " + ", ".join(f"tier {k}: {v:.4f}" for k, v in mond["thresholds"].items()) + "\n")

        if "ebm_global_importance" in block:
            add("### EBM global importance (top 10)\n")
            add("| Feature | Mean absolute contribution (log-odds) |")
            add("|---|---|")
            for item in block["ebm_global_importance"][:10]:
                add(f"| `{item['feature']}` | {item['importance']:.4f} |")
            add("")

    shift = results["distribution_shift_real_to_simulated"]
    add("\n## Distribution shift: model trained on real, applied to simulated\n")
    add("| Model | n | AUC | PR-AUC | Brier | Accuracy |")
    add("|---|---|---|---|---|---|")
    for name, m in shift.items():
        add(f"| {name} | {m['n']} | {m['auc']:.4f} | {m['pr_auc']:.4f} | {m['brier']:.4f} | {m['accuracy_at_threshold']:.4f} |")
    add("")

    th = results["time_holdout_real"]
    add("\n## Time holdout (train <= 2025-03, test >= 2025-04, EBM)\n")
    add(f"Train rows {th['train_rows']}, test rows {th['test_rows']}: AUC {th['test']['auc']:.4f}, "
        f"PR-AUC {th['test']['pr_auc']:.4f}, Brier {th['test']['brier']:.4f}.\n")

    va = results["vouch_analysis"]
    add("\n## Vouch data: can it explain a bureau-score drop?\n")
    add(f"- Real borrowers with any vouch: **{va['coverage']['real_borrowers_with_vouch_rows']}** "
        f"of {va['coverage']['real_borrowers']}")
    add(f"- Simulated borrowers with any vouch: **{va['coverage']['simulated_borrowers_with_vouch']}** "
        f"of {va['coverage']['simulated_borrowers']}")
    add(f"- Max vouches for one borrower: **{va['coverage']['max_vouches_per_borrower']}**\n")
    add("| Vouches | n | Default rate |")
    add("|---|---|---|")
    for k, v in va["default_by_vouch_count"].items():
        add(f"| {k} | {v['n']} | {v['default_rate'] if v['default_rate'] is not None else 'n/a'} |")
    add("")
    add("| Bureau-shock proxy | n bad + vouch | n bad, no vouch | Default + vouch | Default, no vouch | Difference [95% CI] |")
    add("|---|---|---|---|---|---|")
    for k, v in va["bureau_shock_crosstab"].items():
        d = v["difference"]
        add(f"| {k} | {v['n_bad_with_vouch']} | {v['n_bad_without_vouch']} | {v['default_with_vouch']} "
            f"| {v['default_without_vouch']} | {d['diff']} [{d['ci_low']}, {d['ci_high']}] |")
    add("")
    inc = va["incremental_auc"]
    add(f"Adding vouch features to a simulated model: AUC {inc['auc_without_vouch']:.4f} -> "
        f"{inc['auc_with_vouch']:.4f} (delta {inc['delta']['delta_auc']:+.4f}, "
        f"95% CI [{inc['delta']['ci_low']}, {inc['delta']['ci_high']}], "
        f"significant: {inc['delta']['significant']}).\n")
    add(f"**Verdict:** {va['verdict']['recommendation']}\n")

    if "vouch_shock" in results:
        vs = results["vouch_shock"]
        add("\n## Option A: Market-Shock Vouch Evaluation (bureau drop vs vouch held)\n")
        add(f"Evaluated on **{vs['n_samples']}** shock borrowers across **{vs['n_features']}** pre-decision features.\n")
        add("| Model | n | AUC | PR-AUC | Brier | KS | Accuracy | F1 | Approval rate |")
        add("|---|---|---|---|---|---|---|---|---|")
        for name, m in vs["models"].items():
            add(_row(name, m))
        add("")

        if "shock_vouch_crosstab" in vs:
            add("### Default Rate by Bureau Drop and Vouch Status\n")
            add("| Group | n | Default rate | Mean Bureau Drop | Mean Vouch Score |")
            add("|---|---|---|---|---|")
            for grp, info in vs["shock_vouch_crosstab"].items():
                d_rate = f"{info['default_rate']:.2%}" if info['default_rate'] is not None else "n/a"
                b_drop = f"{info['mean_bureau_drop']:.1f}" if info['mean_bureau_drop'] is not None else "n/a"
                v_score = f"{info['mean_vouch_score']:.1f}" if info['mean_vouch_score'] is not None else "n/a"
                add(f"| `{grp}` | {info['n']} | {d_rate} | {b_drop} | {v_score} |")
            add("")

        if vs.get("vouch_risk_reduction_effect") and vs["vouch_risk_reduction_effect"]["diff"] is not None:
            eff = vs["vouch_risk_reduction_effect"]
            add(f"**Vouch Protection Effect:** In borrowers with a bureau drop <= -30 points, holding a vouch changes "
                f"default rate by **{eff['diff']:+.2%}** (95% CI: [{eff['ci_low']:+.2%}, {eff['ci_high']:+.2%}]).\n")

    add("\n## Worked examples (EBM + conformal, 90%)\n")
    for ex in results["examples"]:
        add(f"### {ex['case']} — borrower {ex['borrower_id']}")
        add(f"Default probability {ex['default_probability']:.4f}; conformal set "
            f"repay={ex['conformal_set']['repay']}, default={ex['conformal_set']['default']} -> **{ex['decision']}**")
        for r in ex["reasons"]["positive_factors"]:
            add(f"- (+) {r['text']} (`{r['code']}`, {r['log_odds']:+.4f})")
        for r in ex["reasons"]["risk_factors"]:
            add(f"- (-) {r['text']} (`{r['code']}`, {r['log_odds']:+.4f})")
        for g in ex["missing_information"]:
            add(f"- missing: {g['text']} (`{g['status']}`)")
        add("")

    add("\n## Caveats\n")
    for c in results["caveats"]:
        add(f"- {c}")

    path = os.path.join(RESULTS_DIR, "report.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote", path)
